import os as _os, sys as _sys  # v9.7.407: resolve the tools-local emitter from any cwd
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
from _console import emit  # noqa: E402
from tracked_file_policy import check_default_r_device_outputs  # noqa: E402
import argparse, logging, os, sys
from pathlib import Path

# The cut preserves source text after the declared omissions below.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scanner_hmm_release_policy import is_provisioned_scanner_asset  # noqa: E402
from mamey.privacy_profile import (  # noqa: E402
    PrivacyProfileError, PublicExportPolicy, load_public_export_policy,
    verify_public_file_hold_omissions,
)

# Files that legitimately differ between tiers (build metadata) — never expected to match.
METADATA_SKIP = {"SOURCE_CHECKSUMS_SHA256.txt", "TIER_MANIFEST.txt",
                 "BUNDLE_FINGERPRINT.txt", "CHANGELOG.md",
                 # Regenerated by in-tier tests from the staged public tree, then passed through
                 # the documentation privacy transform and release audit a second time.
                 "docs/BUNDLE_CAPABILITIES.md", "TOOLS_INVENTORY.generated.md",
                 # v9.7.274: BUILD_STAMP.txt's `tier=` field is now set per tier (to match
                 # TIER_MANIFEST), so it legitimately differs from the source's tier=CODE.
                 "BUILD_STAMP.txt"}

# Directories the cut legitimately STRIPS from the public/code tier (make_public_tier.sh: strip_internal
# + the caches removed at stage-1). A private-tree file under one of these has no public counterpart BY
# DESIGN — it is not drift. Kept in sync with make_public_tier.sh so the verifier mirrors the cut; add a
# dir here whenever the cut learns to strip it (v9.7.382: _CANDIDATE_NOTES/ was added to strip_internal).
# Exact correspondence-file omission shared with the tier builder; the patch remains shipped.
STRIP_FILE_PATHS = {"tools/upstream_gtotree2/NOTE_TO_GTOTREE_AUTHOR.md"}

STRIP_DIR_PREFIXES = (
    "_CANDIDATE_NOTES/", "docs/internal/", "tools/internal/", "scripts/one-off/",
    "future_improvements/", "private/", "cohort/", "merged_cohort/", "data/",
    "release2_source_library/", "docs/legacy/", "offline_deps/",
    ".pytest_cache/", "__pycache__/", ".git/",
)

import re as _re
# VTD-01 (v9.7.396): the dynamic-run-dir check was `first.startswith("runs")` — a bare prefix
# match with no word-boundary, so ANY root-level file or directory whose name merely starts with
# the substring "runs" (e.g. "runsafe_check.py", "runsanalysis_helper.md" — ordinary, plausible
# names for a future root-level script or doc in an actively-developed project whose own .395
# CHANGELOG entry describes routine root-file churn) was wrongly classified as "stripped by
# design" and silently excluded from the whole redaction-parity comparison loop -- the exact same
# "silently narrows what actually gets checked" bug shape this file's own v9.7.374 fix (a few
# lines below) explicitly closed for files missing from the public tree entirely. Reproduced:
# _is_stripped("runsafe_check.py") returned True on pristine .395, though it is not a dynamic
# run-output directory at all. Require "runs" to be followed by a genuine boundary (end of
# string, or -/_/. before the rest of the name) so "runs", "runs-old", "runs_2026" still match
# but an unrelated root-level name merely starting with the same four letters does not.
_RUNS_DIR_RE = _re.compile(r"^runs($|[-_.])")


def _is_policy_stripped(rel: str, policy: PublicExportPolicy) -> bool:
    """Omissions the DECLARED export policy is responsible for, as opposed to the structural
    ones above. Kept separate so a reader can tell which of the two authorities excluded a path."""
    normalized = rel.replace(os.sep, "/").lstrip("./")
    directory_parts = normalized.split("/")[:-1]
    if any(part in policy.excluded_root_names for part in directory_parts):
        return True
    return any(normalized == item or normalized.startswith(item + "/")
               for item in policy.excluded_relative_paths)


def _is_stripped(rel: str, policy: PublicExportPolicy | None = None) -> bool:
    """Mirror the code/public cut's structural omissions.

    Root-level run directories are named dynamically (runs, runs-old, runs_2026, ...),
    so they cannot be represented safely as a single static path prefix.
    """
    # CODEX_392 rebase: the incoming patch restored `first.startswith("runs")` here, because it
    # was authored before VTD-01. Reapplying it verbatim would have silently reverted that
    # fix and re-excluded any root-level name merely beginning with "runs" from the whole
    # redaction-parity loop. The boundary regex is kept; only the policy term is added.
    policy = policy or load_public_export_policy()
    rel = rel.replace(os.sep, "/")
    if rel.startswith("./"):
        rel = rel[2:]
    first = rel.split("/", 1)[0]
    return (rel in STRIP_FILE_PATHS
            or is_provisioned_scanner_asset(rel)
            or bool(_RUNS_DIR_RE.match(first))
            or _is_policy_stripped(rel, policy)
            or any(rel.startswith(p) for p in STRIP_DIR_PREFIXES))

def redact_text(t: str) -> str:
    """Compatibility name: the cut preserves genuine labels and text."""
    return t

def redact_py(text: str) -> str:
    return text

def redact(path: str, text: str) -> str:
    return text

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("private_tree")
    ap.add_argument("public_tree")
    ap.add_argument("--ext", default=".py,.md,.json,.csv,.txt,.cff,.sh,.yaml,.yml,.toml")
    ap.add_argument("--privacy-profile", default=None,
                    help="optional sapote_privacy_profile_v1 used by the public cut")
    args = ap.parse_args()
    for root in (args.private_tree, args.public_tree):
        if check_default_r_device_outputs(root):
            return 2
    try:
        policy = load_public_export_policy(args.privacy_profile)
    except PrivacyProfileError as exc:
        # Typed refusal on stderr. sys.stderr.write, not print(file=...), because the repo_health
        # ratchet counts print( calls by AST and cannot see the file= keyword — a diagnostic that
        # is already correctly routed would still read as new library debt.
        sys.stderr.write(f"FAIL: invalid privacy profile: {exc}\n")
        return 2
    omitted_file_holds, hold_problems = verify_public_file_hold_omissions(
        args.private_tree, args.public_tree, policy)
    if hold_problems:
        for problem in hold_problems:
            sys.stderr.write("FAIL: " + problem + "\n")
        return 2
    exts = tuple(e if e.startswith(".") else "." + e for e in args.ext.split(","))

    tested = matched = mismatched = skipped = identity = 0
    mismatches = []
    missing_from_public = []
    for root, _, files in os.walk(args.private_tree):
        for fn in files:
            if not fn.endswith(exts): continue
            priv_p = os.path.join(root, fn)
            rel = os.path.relpath(priv_p, args.private_tree)
            relposix = "/" + rel.replace(os.sep, "/")
            # Only exact current source/hash/receipt-bound omissions are admitted.
            if rel.replace(os.sep, "/") in omitted_file_holds:
                continue
            # a file under a dir the cut strips is absent from the public tier BY DESIGN, not drift
            if _is_stripped(rel, policy):
                continue
            pub_p = os.path.join(args.public_tree, rel)
            if not os.path.exists(pub_p):
                # v9.7.374 (audit lane): pre-fix this silently `continue`d — a private file
                # completely ABSENT from the public tree was never counted as tested, matched,
                # mismatched, or skipped, and never appeared anywhere in the report. Live-
                # reproduced: a private-only .py file with no public counterpart produced a clean
                # "OK: public tier matches source text after declared omissions." /
                # exit 0, even though "for every shared content file" silently narrowed to only
                # the files present in BOTH trees. A file dropped entirely is drift too (it is
                # either a legitimate metadata-class omission that belongs in METADATA_SKIP, or a
                # real cut-step failure) — this checker's whole purpose is asserting the public
                # tier IS an exact redaction-view of the private source, so a silently-omitted
                # file must be surfaced, not swallowed.
                missing_from_public.append(rel)
                continue
            if rel.replace(os.sep, "/") in METADATA_SKIP: skipped += 1; continue
            try:
                priv_bytes = Path(priv_p).read_bytes()
                pub_bytes = Path(pub_p).read_bytes()
            except OSError as exc:
                logging.getLogger(__name__).error("FAIL: cannot read derivation input %s: %s", rel, type(exc).__name__)
                return 2
            # tests/ and the synthetic-ID allowlist are deliberately NOT redacted
            # (they carry synthetic fixtures so the in-tier pytest gate stays passable).
            # Policy there is identity between tiers, not redaction-equality.
            if fn.endswith(".py") or "/tests/" in relposix or fn == "test_synthetic_ids.txt":
                identity += 1
                if priv_bytes == pub_bytes:
                    matched += 1
                else:
                    mismatched += 1; mismatches.append(rel + "  (expected identical, unredacted)")
                continue
            try:
                # Strict decoding preserves errors; documentation uses the redactor's
                # existing universal-newline comparison semantics.
                priv = priv_bytes.decode("utf-8", errors="strict").replace("\r\n", "\n").replace("\r", "\n")
                pub = pub_bytes.decode("utf-8", errors="strict").replace("\r\n", "\n").replace("\r", "\n")
            except UnicodeError:
                logging.getLogger(__name__).error("FAIL: invalid UTF-8 derivation input %s", rel)
                return 2
            tested += 1
            if redact(rel, priv) == pub:
                matched += 1
            else:
                mismatched += 1; mismatches.append(rel)

    emit(f"text-checked      : {tested}", f"identity-checked  : {identity}  (Python + tests/ + synthetic allowlist; not redacted by policy)", f"all checks passed : {matched}", f"metadata skipped  : {skipped}", f"MISMATCHES        : {mismatched}", sep="\n")
    for m in mismatches[:25]:
        emit("   DRIFT:", m)
    emit(f"MISSING_FROM_PUBLIC : {len(missing_from_public)}  (private file has no public counterpart at all)")
    for m in missing_from_public[:25]:
        emit("   MISSING:", m)
    if mismatched or missing_from_public:
        if missing_from_public:
            emit(f"\n{len(missing_from_public)} private file(s) have NO public-tier counterpart at all — "
                  "either add them to METADATA_SKIP if this is a legitimate build-metadata omission, "
                  "or investigate the cut step that dropped them.", file=sys.stderr)
        emit("\nFAIL: public tier differs from the selected source text.", file=sys.stderr)
        return 1
    emit("\nOK: public tier matches source text after declared omissions.")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
