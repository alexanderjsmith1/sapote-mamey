#!/usr/bin/env bash
# release_cut.sh — one-command, gate-enforced release cut.
#
# Sequence (each step is easy to get wrong by hand):
#   1. author writes the CHANGELOG entry (bold-bullet headlines) BEFORE running this
#   2. atomically bump SSOT version + BUILD_STAMP + TIER_MANIFEST stamp
#   3. sync_version propagates the version everywhere
#   4. sync the README release footer (verify_release_identity checks README carries ver+build)
#   5. refresh source-stage membership/checksums after all source mutations
#   6. run the suite once to measure the stale-manifest baseline
#   7. converge RELEASE_MANIFEST, refresh integrity, then require a final green suite
#   8. bind the final green log and refresh source integrity one last time
#   9. fail closed if backup/editor debris exists; never silently delete it
#  10. gates: sync --check, manifest --check, verify_release_identity
#  11. cut the CODE tier (its own leak-audit / derivation / checksum gates). v9.7.444: the other four tiers
#      (clean, cohort, merged, public) are disabled; CUT_TIERS="code clean cohort merged public" with
#      SAPOTE_ENABLE_DISABLED_TIERS=1 restores them (see CUT_PROTOCOL.md).
#  12. emit SHA256SUMS + a per-tier receipt
#
# Usage:  tools/release_cut.sh <bundle_version> <src_dir> <out_dir> [build_letter] [--skip-tests]
#         --skip-tests additionally requires PYTEST_RECEIPT=/absolute/receipt.json and
#         PYTEST_RECEIPT_SHA256=<sha256>; a free-text PYTEST_LOG is never sufficient.
#         RELEASE_PYTEST_MODE=partitioned uses distinct measured-baseline and final-PASS
#         receipts and workflow.json. Resume with RELEASE_WORKFLOW_RESUME=1; a failed
#         stage additionally needs RELEASE_WORKFLOW_RETRY=STAGE=reason. It cannot
#         be combined with --skip-tests. Default stays monolithic.
# Date:   pinned via RELEASE_DATE=YYYYMMDD (defaults to today) so a rolled clock can't desync a cut.
# Example: RELEASE_DATE=20260710 tools/release_cut.sh 9.7.258 . ../cut258 a
set -euo pipefail
# pytest writes bytecode during collection before tests/conftest.py can set the
# child-process environment. Start every cut phase with the parent disabled too.
export PYTHONDONTWRITEBYTECODE=1

CUT_FAILURE_STATUS=1
say(){ printf '\n=== %s ===\n' "$*"; }; die(){ printf '\nABORT: %s\n' "$*" >&2; exit "$CUT_FAILURE_STATUS"; }
if [[ "${1:-}" == --help || "${1:-}" == -h ]]; then
  say 'Usage: tools/release_cut.sh VERSION SOURCE OUTPUT [LETTER] [--skip-tests]
Use an explicitly authorized disposable cut source. Source preparation changes
identity/generated metadata; every changed source requires new validation.

Tests: default monolithic baseline and final configured slow/network suite.
Set RELEASE_PYTEST_MODE=partitioned for source-bound serial receipts/resume.
Do not set ambient PYTEST_ADDOPTS. Optional --skip-tests requires both an absolute
PYTEST_RECEIPT and its PYTEST_RECEIPT_SHA256; a log alone is insufficient.

Prerequisites: set PYTHON to one installed Python3.12+ executable, preserving
your virtualenv path (quote paths with spaces); otherwise python3 is selected
from PATH. The shell uses the PYTHON environment setting. Direct
release_workflow.py calls use --python. Inspect failed admission logs for
dependencies, POSIX process monitoring, disk and RSS holds. Resolve the
reported prerequisite; retain failed evidence and keep the same test profile.
Generated metadata: rerun its named owner before source-integrity refresh and
revalidation; stale generated bytes cannot be approved by hashing them alone.
Optional registry diagnostic: omit all four options for NOT_REQUESTED/NOT_RUN,
without synthetic-role or disclosure clearance. If requested, supply
--synthetic-registry ABSOLUTE_TSV plus selected
--synthetic-registry-sha256, --synthetic-guard-sha256 and
--synthetic-allowlist-sha256. Admission exits 0 for a bound snapshot pass, 1 for failure and 2 for a hold, before source
preparation and packaging. No local dataset is discovered; complete fixture
roles/source-disclosure clearance remain separate holds. No cut/seal permission follows from
configuration checks or a scoped registry snapshot result.'
  exit 0
fi

VER="${1:?bundle version, e.g. 9.7.258}"; SRC="${2:?source tree root}"; OUT="${3:?output dir}"
shift 3
LETTER=a; SKIP_TESTS=0
SYNTHETIC_REGISTRY=""; SYNTHETIC_REGISTRY_SHA256=""; SYNTHETIC_GUARD_SHA256=""; SYNTHETIC_ALLOWLIST_SHA256=""
if [[ $# -gt 0 && "$1" != --* ]]; then
  LETTER="$1"; shift
fi
while [[ $# -gt 0 ]]; do
  case "$1" in
    --synthetic-registry) [[ $# -ge 2 && -n "$2" && "$2" != --* && -z "$SYNTHETIC_REGISTRY" ]] || CUT_FAILURE_STATUS=2 die "missing or duplicate --synthetic-registry selection"; SYNTHETIC_REGISTRY="$2"; shift 2; continue ;;
    --synthetic-registry-sha256) [[ $# -ge 2 && -n "$2" && "$2" != --* && -z "$SYNTHETIC_REGISTRY_SHA256" ]] || CUT_FAILURE_STATUS=2 die "missing or duplicate --synthetic-registry-sha256 selection"; SYNTHETIC_REGISTRY_SHA256="$2"; shift 2; continue ;;
    --synthetic-guard-sha256) [[ $# -ge 2 && -n "$2" && "$2" != --* && -z "$SYNTHETIC_GUARD_SHA256" ]] || CUT_FAILURE_STATUS=2 die "missing or duplicate --synthetic-guard-sha256 selection"; SYNTHETIC_GUARD_SHA256="$2"; shift 2; continue ;;
    --synthetic-allowlist-sha256) [[ $# -ge 2 && -n "$2" && "$2" != --* && -z "$SYNTHETIC_ALLOWLIST_SHA256" ]] || CUT_FAILURE_STATUS=2 die "missing or duplicate --synthetic-allowlist-sha256 selection"; SYNTHETIC_ALLOWLIST_SHA256="$2"; shift 2; continue ;;
    --skip-tests) [[ "$SKIP_TESTS" -eq 0 ]] || die "duplicate --skip-tests option"; SKIP_TESTS=1 ;;
    *) die "unknown cut option: $1" ;;
  esac
  shift
done
[[ "$LETTER" =~ ^[a-z]$ ]] || die "build letter must be one lowercase letter"
[[ -z "${PYTEST_ADDOPTS:-}" ]] || die "PYTEST_ADDOPTS overrides the release test profile; unset it and retry before source preparation."
REGISTRY_ARGS=()
if [[ -n "$SYNTHETIC_REGISTRY$SYNTHETIC_REGISTRY_SHA256$SYNTHETIC_GUARD_SHA256$SYNTHETIC_ALLOWLIST_SHA256" ]]; then
  REGISTRY_ARGS=(--synthetic-registry "$SYNTHETIC_REGISTRY" --synthetic-registry-sha256 "$SYNTHETIC_REGISTRY_SHA256"
                 --synthetic-guard-sha256 "$SYNTHETIC_GUARD_SHA256" --synthetic-allowlist-sha256 "$SYNTHETIC_ALLOWLIST_SHA256")
fi
# BEGIN RELEASE PYTHON LOCATOR
# Resolve before any cwd change; retain the lexical virtualenv prefix.
CUT_PYTHON_CHOICE="${PYTHON:-python3}"
if [[ "$(type -t "$CUT_PYTHON_CHOICE" || true)" != file ]] || ! PYTHON="$(command -v "$CUT_PYTHON_CHOICE")"; then
  CUT_FAILURE_STATUS=2 die "[RELEASE-PYTHON-001] Select one installed executable with PYTHON before source preparation."
fi
case "$PYTHON" in /*) ;; *) PYTHON="$PWD/$PYTHON" ;; esac
# Remove only /./ components; retain .. and virtualenv symlink prefixes.
while [[ "$PYTHON" == */./* ]]; do PYTHON="${PYTHON//\/.\///}"; done
if [[ ! -f "$PYTHON" || ! -x "$PYTHON" ]]; then
  CUT_FAILURE_STATUS=2 die "[RELEASE-PYTHON-001] PYTHON must select one executable file, not a command string."
fi
if ! CUT_PYTHON_PROBE="$("$PYTHON" -c 'import sys; supported = sys.version_info >= (3, 12); sys.stdout.write("SAPOTE_EXPORT_PYTHON_3_12_PLUS" if supported else ""); raise SystemExit(0 if supported else 2)' 2>/dev/null)" || [[ "$CUT_PYTHON_PROBE" != SAPOTE_EXPORT_PYTHON_3_12_PLUS ]]; then
  CUT_FAILURE_STATUS=2 die "[RELEASE-PYTHON-002] Select an installed Python3.12+ with the required compatibility response."
fi
# The locator is already absolute; preserve symlink-directory/.. semantics.
export PYTHON
# END RELEASE PYTHON LOCATOR
DATE="${RELEASE_DATE:-$(date +%Y%m%d)}"
STAMP="${DATE}v$(echo "$VER" | tr -d '.')${LETTER}"
CUT_OUTPUT_OCCUPIED=0
[[ ! -e "$OUT" && ! -L "$OUT" ]] || CUT_OUTPUT_OCCUPIED=1
# Bind both caller-supplied paths before changing directory. Admission is read-only.
if ! SRC="$("$PYTHON" -c 'from pathlib import Path; import sys; p=Path(sys.argv[1]).resolve(strict=True); p.is_dir() or sys.exit(2); print(p)' "$SRC" 2>/dev/null)"; then
  CUT_FAILURE_STATUS=2 die "[RELEASE-PATH-001] Source must name an existing directory; resolve it before source preparation."
fi
if ! OUT="$("$PYTHON" -c 'from pathlib import Path; import sys; print(Path(sys.argv[1]).resolve())' "$OUT" 2>/dev/null)"; then
  CUT_FAILURE_STATUS=2 die "[RELEASE-PATH-001] Output path could not be resolved from the caller directory."
fi
if ! "$PYTHON" - "$SRC" "$OUT" <<'PY'
from pathlib import Path
import sys
source, output = map(Path, sys.argv[1:])
raise SystemExit(2 if output.is_relative_to(source) or source.is_relative_to(output) else 0)
PY
then
  CUT_FAILURE_STATUS=2 die "[RELEASE-PATH-002] Source and output must be separate trees; choose an output outside the source and its ancestors."
fi
cd "$SRC"
PYTEST_MODE="${RELEASE_PYTEST_MODE:-monolithic}"
[[ "$PYTEST_MODE" == monolithic || "$PYTEST_MODE" == partitioned ]] || die "unknown RELEASE_PYTEST_MODE: $PYTEST_MODE"
[[ "$PYTEST_MODE" != partitioned || "$SKIP_TESTS" -eq 0 ]] || die "partitioned mode cannot use --skip-tests."
receipt_sha256(){
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1"; else shasum -a 256 "$1"; fi | awk '{print $1}'
}

PHASE="${RELEASE_WORKFLOW_PHASE:-}"
# A new monolithic attempt must never truncate a prior baseline/final log.
# Partitioned resume and declared internal phases retain their own owner gates.
if [[ -z "$PHASE" && "$PYTEST_MODE" == monolithic && "$CUT_OUTPUT_OCCUPIED" -ne 0 ]]; then
  CUT_FAILURE_STATUS=2 die "[RELEASE-PATH-003] Output is occupied; preserve prior evidence and choose a fresh output directory before source preparation."
fi
# Admit required external-receipt settings before any source preparation.
# Exact source/environment/log verification remains at its existing later gate.
if [[ -z "$PHASE" && "$SKIP_TESTS" -eq 1 ]]; then
  [[ -n "${PYTEST_RECEIPT:-}" && "$PYTEST_RECEIPT" = /* ]] \
    || CUT_FAILURE_STATUS=2 die "[RELEASE-RECEIPT-001] --skip-tests requires PYTEST_RECEIPT=/absolute/path/to/a structured external-validation receipt before source preparation."
  [[ "${PYTEST_RECEIPT_SHA256:-}" =~ ^[0-9a-f]{64}$ ]] \
    || CUT_FAILURE_STATUS=2 die "[RELEASE-RECEIPT-002] --skip-tests requires PYTEST_RECEIPT_SHA256=<64 lowercase hex characters> before source preparation."
  [[ -f "$PYTEST_RECEIPT" ]] \
    || CUT_FAILURE_STATUS=2 die "[RELEASE-RECEIPT-003] External receipt file is unavailable; preserve prior evidence and select an existing receipt before source preparation."
fi
if [[ "$PYTEST_MODE" == partitioned && -z "$PHASE" ]]; then
  args=(cut --python "$PYTHON" --version "$VER" --source "$SRC" --out "$OUT" --letter "$LETTER" --date "$DATE"
        --files-per-partition "${RELEASE_PARTITION_FILES:-20}" ${REGISTRY_ARGS[@]+"${REGISTRY_ARGS[@]}"})
  [[ "${RELEASE_WORKFLOW_RESUME:-0}" == 0 ]] || args+=(--resume)
  [[ -z "${RELEASE_WORKFLOW_RETRY:-}" ]] || args+=(--retry "$RELEASE_WORKFLOW_RETRY")
  unset RELEASE_WORKFLOW_RESUME RELEASE_WORKFLOW_RETRY
  exec "$PYTHON" "$SRC/tools/release_workflow.py" "${args[@]}"
fi
source "$SRC/tools/cut_preflight.sh"

assert_no_backup_debris(){
  local offender
  offender="$(find . -type f \( -name '*-E' -o -name '*.orig' -o -name '*.rej' -o -name '*.bak' -o -name '*~' \) ! -path './.git/*' -print -quit)"
  [[ -z "$offender" ]] || die "backup/editor debris present: $offender — remove or adjudicate it before cutting."
}

# Source integrity necessarily becomes stale after a patch, version sync, generated-surface update,
# or RELEASE_MANIFEST rewrite. Regenerate both records from the tier builder's tracked-file policy;
# SOURCE_CHECKSUMS includes TIER_MANIFEST, excludes itself, and is written last.
refresh_source_integrity(){
  local tier_tmp
  tier_tmp="$(mktemp)"
  "$PYTHON" tools/tracked_file_policy.py --emit-manifest . code "$VER" "$STAMP" > "$tier_tmp"
  # mktemp is private by default; the generated source manifest is shipped/readable metadata.
  chmod 0644 "$tier_tmp"
  mv "$tier_tmp" TIER_MANIFEST.txt
  "$PYTHON" - "$SRC" <<'PY'
import hashlib
import pathlib
import sys

root = pathlib.Path(sys.argv[1]).resolve()
sys.path.insert(0, str(root / "tools"))
from tracked_file_policy import tracked_paths

paths = [p[2:] if p.startswith("./") else p for p in tracked_paths(root)]
paths.append("TIER_MANIFEST.txt")
rows = []
for rel in sorted(set(paths), key=lambda value: value.encode()):
    digest = hashlib.sha256((root / rel).read_bytes()).hexdigest()
    rows.append(f"{digest}  ./{rel}\n")
tmp = root / "SOURCE_CHECKSUMS_SHA256.txt.tmp"
tmp.write_text("".join(rows), encoding="utf-8")
tmp.replace(root / "SOURCE_CHECKSUMS_SHA256.txt")
PY
  "$PYTHON" tools/check_release_manifest.py --root . --quiet
}

pytest_counts(){
  "$PYTHON" - "$1" <<'PY'
import pathlib
import re
import sys

text = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace")
summary = None
pattern = re.compile(r"\b\d+\s+passed\b.*\bin\s+\d+(?:\.\d+)?s\b")
for line in text.splitlines():
    if pattern.search(line):
        summary = line
if summary is None:
    raise SystemExit("pytest log has no complete terminal summary")
passed = re.search(r"(\d+)\s+passed\b", summary)
skipped = re.search(r"(\d+)\s+skipped\b", summary)
print(passed.group(1), skipped.group(1) if skipped else "0")
PY
}


registry_preflight(){
  local code
  if "$PYTHON" tools/release_workflow.py _registry --python "$PYTHON" --source "$SRC" ${REGISTRY_ARGS[@]+"${REGISTRY_ARGS[@]}"}; then
    return 0
  else
    code=$?; [[ "$code" -eq 1 ]] || code=2
    CUT_FAILURE_STATUS="$code" die "registry preflight refused; reconcile explicit selections and guard roles before source preparation or packaging."
  fi
}

prepare_release(){
registry_preflight
say "validate CHANGELOG top entry for v$VER"
head -1 CHANGELOG.md | grep -q "v$VER" || die "CHANGELOG top entry is not v$VER — write it first."
# grep reads the whole entry (no -q): under pipefail, -q closes the pipe at the first match, awk dies of SIGPIPE on a long
# entry, and the cut aborted with "no bold bullets" although the bullets were there.
awk 'NR>1 && /^# v9/{exit} {print}' CHANGELOG.md | grep -E '^- \*\*' >/dev/null \
  || die "CHANGELOG v$VER entry has no '- **bold**' bullets (patch-line parser needs them)."

say "preflight: no backup/editor debris"
assert_no_backup_debris
sapote_assert_no_review_root "$SRC" || die "review-stage root preflight failed."
sapote_purge_cut_bytecode "$SRC" || die "working-copy bytecode purge failed."

say "atomically bump to $VER / $STAMP"
"$PYTHON" tools/rewrite_release_identity.py "$VER" "$STAMP" --root .

say "sync_version (propagate)"; "$PYTHON" tools/sync_version.py >/dev/null
# (sync_version maintains the README "Current bundle: v… / engine … · build …" footer itself)
"$PYTHON" -c "import sys; sys.path.insert(0,'tools'); import sync_version as sv; sv.sync_build_stamp_patch(check=False)"
"$PYTHON" tools/render_bootstrap_contract.py --apply >/dev/null
"$PYTHON" tools/gen_command_catalog.py >/dev/null
"$PYTHON" tools/generate_deliverables_menu.py --apply >/dev/null
"$PYTHON" tools/gen_tools_inventory.py >/dev/null

say "refresh current module inventory"
"$PYTHON" tools/check_module_accretion.py --write >/dev/null \
  || die "module inventory refresh failed."

say "refresh file atlas from current source"
"$PYTHON" tools/file_atlas.py --out docs/FILE_ATLAS.csv --md docs/FILE_ATLAS.md >/dev/null \
  || die "file atlas regeneration failed."
"$PYTHON" tools/gen_tools_inventory.py --maintenance >/dev/null
"$PYTHON" tools/generated_surface_ownership.py --root . --phase source-generated --assert-input none --assert-final module_manifest,tools_inventory,file_atlas >/dev/null \
  || die "source-generated ownership admission refused; include the atlas owner and both outputs before maintenance/source validation."

say "gate: version sync"
"$PYTHON" tools/sync_version.py --check | tail -1 | grep -q "OK" || die "version sync gate failed."
}

# Keep the default path in execution order; internal phases skip its suite.
if [[ -z "$PHASE" ]]; then
prepare_release
mkdir -p "$OUT"
DEFAULT_PYTEST_LOG="$OUT/pytest_full_suite_${STAMP}.log"
if [[ "$SKIP_TESTS" -eq 0 ]]; then
  BASELINE_PYTEST_LOG="$OUT/pytest_manifest_baseline_${STAMP}.log"
  PYTEST_LOG="${PYTEST_LOG:-$DEFAULT_PYTEST_LOG}"
  say "refresh source-stage integrity before manifest convergence"
  refresh_source_integrity || die "source-stage integrity refresh failed."
  say "measure full-suite baseline (stale-manifest failures may occur only in this run)"
  set +e
  PYTHONPATH=. "$PYTHON" -m pytest -q -p no:cacheprovider --run-slow --run-network >"$BASELINE_PYTEST_LOG" 2>&1
  BASELINE_RC=$?
  set -e
  read -r BASE_PASSED BASE_SKIPPED < <(pytest_counts "$BASELINE_PYTEST_LOG") \
    || die "could not extract measured counts from baseline pytest log."
  echo "  baseline: $(tail -1 "$BASELINE_PYTEST_LOG") (exit $BASELINE_RC; evidence seed only)"
  say "converge release manifest against its consumer tests"
  "$PYTHON" tools/gen_release_manifest.py --fixed-point \
    --tests-passed "$BASE_PASSED" --tests-skipped "$BASE_SKIPPED" >/dev/null \
    || die "release manifest fixed-point convergence failed."
  refresh_source_integrity || die "post-convergence source integrity refresh failed."
  say "gate: final full suite"
  if ! PYTHONPATH=. "$PYTHON" -m pytest -q -p no:cacheprovider --run-slow --run-network >"$PYTEST_LOG" 2>&1; then
    tail -20 "$PYTEST_LOG" >&2
    die "final full suite has failures — fix before cutting."
  fi
else
  say "gate: verify exact-source external full-suite receipt"
  [[ -n "${PYTEST_RECEIPT:-}" && "$PYTEST_RECEIPT" = /* ]] \
    || die "--skip-tests requires PYTEST_RECEIPT=/absolute/path/to/a structured external-validation receipt."
  [[ "${PYTEST_RECEIPT_SHA256:-}" =~ ^[0-9a-f]{64}$ ]] \
    || die "--skip-tests requires PYTEST_RECEIPT_SHA256=<64 lowercase hex characters>."
  RECEIPT_VERIFIER="tools/verify_external_validation_receipt.py"
  [[ -f "$RECEIPT_VERIFIER" ]] \
    || die "external-validation receipt verifier is missing: $RECEIPT_VERIFIER"
  if ! PYTEST_LOG="$("$PYTHON" "$RECEIPT_VERIFIER" --root . --receipt "$PYTEST_RECEIPT" \
      --expected-receipt-sha256 "$PYTEST_RECEIPT_SHA256" --print-log-path)"; then
    die "external full-suite receipt is invalid; refusing --skip-tests."
  fi
  echo "  external validation receipt: PASS ($PYTEST_RECEIPT)"
  echo "  verified pytest log: $PYTEST_LOG"
fi
grep -qE '[0-9]+ passed' "$PYTEST_LOG" \
  || die "pytest log has no passed-count summary: $PYTEST_LOG"
grep -qE '[1-9][0-9]* (failed|error|errors)' "$PYTEST_LOG" \
  && die "pytest log records failures/errors: $PYTEST_LOG"
echo "  $(tail -1 "$PYTEST_LOG")"

say "generate release manifest from final green suite"
"$PYTHON" tools/gen_release_manifest.py --apply --pytest-log "$PYTEST_LOG" >/dev/null
refresh_source_integrity || die "final source integrity refresh failed."
"$PYTHON" tools/gen_release_manifest.py --check --pytest-log "$PYTEST_LOG" >/dev/null \
  || die "release manifest does not match final identity/test log."
fi

post_test_gates(){
"$PYTHON" tools/file_atlas.py --check >/dev/null \
  || die "file atlas is stale or its freshness owner is unavailable; regenerate with python3 tools/file_atlas.py --out docs/FILE_ATLAS.csv --md docs/FILE_ATLAS.md, then revalidate."
"$PYTHON" tools/generated_surface_ownership.py --root . --phase source-final --assert-input module_manifest,tools_inventory,file_atlas --assert-final module_manifest,tools_inventory,file_atlas,version_build,release_manifest >/dev/null \
  || die "source-final ownership admission refused; preserve generated owners and release-manifest validation before packaging."
"$PYTHON" tools/render_bootstrap_contract.py --check >/dev/null \
  || die "bootstrap generated surfaces drifted after synchronization; run python3 tools/render_bootstrap_contract.py --apply, then refresh source integrity and revalidate."
"$PYTHON" tools/gen_command_catalog.py --check >/dev/null \
  || die "generated command catalog drifted after synchronization; run python3 tools/gen_command_catalog.py, then refresh source integrity and revalidate."
"$PYTHON" tools/generate_deliverables_menu.py --check >/dev/null \
  || die "generated deliverables menu drifted after synchronization."
"$PYTHON" tools/gen_tools_inventory.py --check >/dev/null \
  || die "generated tools inventory drifted after synchronization."
"$PYTHON" tools/gen_tools_inventory.py --maintenance --check >/dev/null \
  || die "generated maintenance inventory drifted after synchronization; run python3 tools/gen_tools_inventory.py --maintenance after its input owners, then refresh source integrity and revalidate."
"$PYTHON" tools/rewrite_release_identity.py "$VER" "$STAMP" --root . --check >/dev/null \
