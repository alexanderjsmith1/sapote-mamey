#!/usr/bin/env python3
"""Figure options list: every registered figure tool and the options a person or an LLM can set on it.

Reads the registry `mamey/data/figure_tools.json` (figure-type ID -> tool, name, what it draws) and runs each tool's
own `--help` (and each subcommand's), so the list always matches the code. Writes:

  docs/FIGURE_OPTIONS.generated.md     for people: one section per figure type, a table of options
  docs/figure_options.generated.json   for LLMs: the same, machine-readable (flag, value name, choices, default, help)

`--check` exits 1 when either file differs from what the code would generate now (for a test or a cut check).
A tool whose `--help` fails is listed with the error, never silently dropped.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "mamey/data/figure_tools.json"
MD_OUT = ROOT / "docs/FIGURE_OPTIONS.generated.md"
JSON_OUT = ROOT / "docs/figure_options.generated.json"
SKIP = {"-h", "--help"}
OPT_LINE = re.compile(r"^  (-\S.*?)(?:\s{2,}(\S.*))?$")


def run_help(tool: Path, sub: str | None = None) -> tuple[str, str]:
    cmd = [sys.executable, str(tool)] + ([sub] if sub else []) + ["--help"]
    p = subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT, timeout=120,
                       env={**os.environ, "COLUMNS": "200", "PYTHONDONTWRITEBYTECODE": "1"})
    return (p.stdout, "") if p.returncode == 0 else ("", (p.stderr or p.stdout).strip().splitlines()[-1:][0] if (p.stderr or p.stdout).strip() else f"exit {p.returncode}")


def parse_help(text: str) -> tuple[list[dict], list[str]]:
    """argparse help -> (options, subcommands). Handles wrapped help lines and {a,b} choices."""
    opts, subs, cur, section = [], [], None, ""
    for line in text.splitlines():
        if line and not line.startswith(" "):
            section = line.strip().rstrip(":").lower()
            cur = None
            continue
        if section.startswith("positional") and re.match(r"^  \{([^}]+)\}", line):
            subs = re.match(r"^  \{([^}]+)\}", line).group(1).split(",")
            continue
        m = OPT_LINE.match(line)
        if m and section not in ("usage",) and not section.startswith("positional"):
            spec, helptext = m.group(1).strip(), (m.group(2) or "").strip()
            names = [s.split()[0] for s in spec.split(", ")]
            flag = next((n for n in names if n.startswith("--")), names[0])
            if flag in SKIP:
                cur = None
                continue
            rest = spec.split(", ")[-1].split(maxsplit=1)
            value = rest[1] if len(rest) > 1 else ""
            choices = value[1:-1].split(",") if value.startswith("{") and value.endswith("}") else []
            cur = {"flag": flag, "value": "" if choices else value, "choices": choices, "help": helptext}
            opts.append(cur)
        elif cur is not None and line.startswith(" " * 6) and line.strip():
            cur["help"] = (cur["help"] + " " + line.strip()).strip()
    for o in opts:
        d = re.search(r"\(default:?\s*([^)]*)\)", o["help"])
        o["default"] = d.group(1).strip() if d else ""
    return opts, subs


def collect() -> dict:
    reg = json.loads(REGISTRY.read_text())
    out = []
    for fig in reg["figures"]:
        tool = ROOT / fig["tool"]
        entry = {k: fig[k] for k in ("id", "name", "draws", "tool")}
        entry["note"] = fig.get("note", "")
        if not tool.exists():
            entry.update(status="TOOL_NOT_IN_THIS_TREE", commands=[])
            out.append(entry)
            continue
        text, err = run_help(tool)
        if err:
            entry.update(status=f"HELP_FAILED: {err}", commands=[])
            out.append(entry)
            continue
        opts, subs = parse_help(text)
        cmds = [{"command": "", "options": opts}] if not subs else []
        for s in subs:
            t2, e2 = run_help(tool, s)
            cmds.append({"command": s, "options": parse_help(t2)[0] if not e2 else [], "error": e2})
        entry.update(status="OK", commands=cmds)
        out.append(entry)
    return {"schema": "sapote.figure_options.v1", "registry": str(REGISTRY.relative_to(ROOT)),
            "common": reg.get("common", []), "figures": out}


def to_md(data: dict) -> str:
    esc = lambda s: s.replace("|", "\\|")
    lines = ["# Figure options (generated)", "",
             "Generated by `tools/gen_figure_options.py` from each tool's own `--help`; do not edit by hand.",
             "Every figure is drawn by its bundle tool with paper-ready defaults. Change a figure by naming its ID and the "
             "option, for example \"B04 with --count-labels none\". Machine-readable copy: `docs/figure_options.generated.json`.", ""]
    if data["common"]:
        lines += ["## Options most figure tools share", ""] + [f"- `{c['flag']}`: {c['help']}" for c in data["common"]] + [""]
    lines += ["## Index", "", "| ID | Figure | Tool | Status |", "|---|---|---|---|"]
    lines += [f"| {f['id']} | {esc(f['name'])} | `{f['tool']}` | {f['status']} |" for f in data["figures"]] + [""]
    for f in data["figures"]:
        lines += [f"## {f['id']}: {f['name']}", "", f["draws"], ""]
        if f["note"]:
            lines += [f"Note: {f['note']}", ""]
        lines += [f"Tool: `{f['tool']}`. Status: {f['status']}.", ""]
        for c in f["commands"]:
            if c["command"]:
                lines += [f"### `{c['command']}`", ""]
            if c.get("error"):
                lines += [f"Help failed: {c['error']}", ""]
                continue
            lines += ["| Option | Value | Choices | Default | What it does |", "|---|---|---|---|---|"]
            lines += [f"| `{o['flag']}` | {esc(o['value'])} | {esc(', '.join(o['choices']))} | {esc(o['default'])} | {esc(o['help'])} |"
                      for o in c["options"]] + [""]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if the generated files are out of date")
    a = ap.parse_args(argv)
    data = collect()
    md, js = to_md(data), json.dumps(data, indent=1) + "\n"
    if a.check:
        stale = [p.name for p, t in ((MD_OUT, md), (JSON_OUT, js)) if not p.exists() or p.read_text() != t]
        print("figure options: " + ("up to date" if not stale else "STALE: " + ", ".join(stale)))
        return 1 if stale else 0
    MD_OUT.write_text(md)
    JSON_OUT.write_text(js)
    bad = [f["id"] for f in data["figures"] if f["status"] != "OK"]
    print(f"wrote {MD_OUT.relative_to(ROOT)} and {JSON_OUT.relative_to(ROOT)}: {len(data['figures'])} figure types"
          + (f"; not OK: {', '.join(bad)}" if bad else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
