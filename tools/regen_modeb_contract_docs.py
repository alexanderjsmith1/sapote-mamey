def _section_span(sections: list[dict]) -> str:
    if not sections:
        return "no declared sections"
    numbers = [section["number"] for section in sections]
    if numbers == list(range(numbers[0], numbers[-1] + 1)):
        return f"§{numbers[0]}–§{numbers[-1]}"
    return ", ".join(f"§{number}" for number in numbers)


def render_titles_doc(contract: dict) -> str:
    """Render the canonical titles doc — section names + a compact required/
    conditional summary."""
    sv = contract.get("schema_version", "?")
    sections = sorted(contract.get("sections", []), key=lambda s: s["number"])
    section_span = _section_span(sections)

    always = [s for s in sections if s.get("required") == "always"]
    lines = [
        f"# Mode B canonical section titles — {section_span} ({len(sections)} declared sections; `{sv}`)",
        "",
        "> **Generated by `tools/regen_modeb_contract_docs.py` from the selected JSON. "
        "Default source: `mamey/data/mode_b/modeb_full30_corrective_contract.json` "
        "(historical filename). Do not edit this output by hand. Maintain generator prose "
        "or the independently approved JSON owner, then regenerate.**",
        "",
        "## One-line rule",
        "",
        "This page lists every section declared by the selected JSON, grouped by its unchanged "
        "base `required` flags. These flags are not the completion rule for every named profile. "
        "The default corrective schema has 48 sections despite its historical full30 filename; "
        "`MODEB_CANDIDATE_30` is a legacy candidate profile. The finished "
        "`FINISHED_FULL48_CURRENT_EVIDENCE` profile requires §§1–48 exactly once and in order, "
        "with its own evidence and reconciliation requirements. Opt-in `current50_v2` has a "
        "separate JSON, titles and verifier contract. Select the actual profile via "
        "`MODEB_PROFILE_MATRIX.md`; do not transfer section maps between profiles. "
        "Preserve the selected schema's exact titles, numbering and order.",
        "",
        "## Named profiles declared in the selected JSON",
        "",
        *[f"- **`{name}`** — {desc}" for name, desc in (contract.get("profiles") or {}).items()],
        "",
        f"## Base schema: always-required sections ({len(always)})",
        "",
    ]

    for s in always:
        lines.append(f"{s['number']}. **{s['title']}**")

    cond = [s for s in sections if s.get("required") == "conditional"]
    if cond:
        lines.extend([
            "",
            f"## Base schema: conditional sections ({len(cond)})",
            "",
            "These base flags apply when the named predicate fires. A selected finished "
            "profile can require stronger coverage; do not infer permission to omit its sections.",
            "",
            "| § | Title | Required when |",
            "|---|---|---|",
        ])
        for s in cond:
            lines.append(
                f"| {s['number']} | **{s['title']}** | {s.get('condition_human','—')} |"
            )

    optional = [s for s in sections if s.get("required") == "optional"]
    if optional:
        lines.extend([
            "", f"## Base schema: optional sections ({len(optional)})", "",
            "Optional is the base schema flag, not a waiver of a selected finished profile's requirements.", "",
            "| § | Title |", "|---|---|",
        ])
        for s in optional:
            lines.append(f"| {s['number']} | **{s['title']}** |")

    lines.extend([
        "",
        "## Non-negotiable schema rules",
        "",
        "- Use the exact section number/title pairs above and the selected profile's coverage rules.",
        "- §7 is **Transport, resistance, and regulation** and §16 is **BLASTP/HMMER next steps**; these titles are often renamed. Do not.",
        "- The default corrective schema's always, conditional and optional flags remain distinct.",
        "- A finished full48 profile has stronger coverage requirements than the legacy candidate/base flags.",
        "- A section named `Manual BLASTP evidence, if present` is obsolete and must fail "
        "the current Full Mode B validator.",
        "- Older `§1–§8`, `§1–§10`, and prior 20-title inventories are historical/scaffold "
        "contracts only; they are not current Full Mode B.",
        "",
        "## Artifact-drift rule",
        "",
        "A real Mode B card is a written interpretation built from evidence. Tables, "
        "FASTA files, PDFs, character counts, and before/after trackers are supporting "
        "artifacts, not acceptance evidence. One BGC must pass the prose-first gate "
        "before scaling to many BGCs.",
        "",
        "## Source of truth",
        "",
        f"This document is generated from `mamey/data/mode_b/"
        f"modeb_full30_corrective_contract.json` (schema `{sv}`). The validator "
        f"`mamey.modeb_structure_gate.lint_card()` and the template emitter "
        f"`mamey emit-modeb-template` both read the JSON directly. The §1–§20 facade "
        f"`mamey.validators.modeb_full20` derives its sections list from the same "
        f"JSON. The default corrective schema declares {len(sections)} sections; its historical "
        f"filename does not limit it to thirty. The opt-in current50_v2 profile has a separate JSON.",
        "",
    ])
    return "\n".join(lines) + "\n"


def render_contract_doc(contract: dict) -> str:
    """Render the full contract spec — section policy, predicates, quality
    gate, complete required/conditional table."""
    sv = contract.get("schema_version", "?")
    superseded = contract.get("supersedes", "—")
    section_policy = contract.get("section_policy", "")
    quality_gate = contract.get("quality_gate", []) or []
    sections = sorted(contract.get("sections", []), key=lambda s: s["number"])
    section_span = _section_span(sections)

    lines = [
        f"# Mode B base-schema contract — {section_span} ({len(sections)} declared sections; `{sv}`)",
        "",
        "> **Generated by `tools/regen_modeb_contract_docs.py` from the selected JSON. "
        "Default source: `mamey/data/mode_b/modeb_full30_corrective_contract.json` "
        "(historical filename). Do not edit this output by hand. Maintain generator prose "
        "or the independently approved JSON owner, then regenerate.**",
        "",
        f"**Schema version:** `{sv}`  ",
        f"**Supersedes:** {superseded}  ",
        f"**Source protocol:** {contract.get('source_protocol', '—')}",
        "",
        "## Section policy",
        "",
        f"{section_policy}",
        "",
        "The table preserves the selected JSON's base required/conditional/optional flags. "
        "A finished named profile can require every section plus additional evidence and reconciliation. "
        "The default full48 schema and opt-in current50_v2 remain separate contract owners; "
        "use MODEB_PROFILE_MATRIX.md and the actual emitted template/verifier.",
        "",
        "## Named profiles declared in the selected JSON",
        "",
        *[f"- **`{name}`** — {desc}" for name, desc in (contract.get("profiles") or {}).items()],
        *([f"", f"{contract['profile_note']}"] if contract.get("profile_note") else []),
        "",
        "## Sections — required/conditional table",
        "",
        "| § | Title | Required | Condition |",
        "|---|---|---|---|",
    ]
    for s in sections:
        req = s.get("required", "?")
        cond = s.get("condition_human", "—") if req == "conditional" else "—"
        lines.append(f"| {s['number']} | **{s['title']}** | {req} | {cond} |")

    # Conditional predicates summary
    cond_sections = [s for s in sections if s.get("required") == "conditional"]
    if cond_sections:
        lines.extend([
            "",
            "## Conditional predicates",
            "",
            "Each conditional section is gated by a named predicate evaluated against the "
            "BGC's context (triage row + strain rollups). The validator "
            "(`mamey.modeb_structure_gate.lint_card`) and template emitter "
            "(`mamey emit-modeb-template`) use the same predicate set, defined in "
            "`mamey/modeb_structure_gate.py::_build_predicates`. The descriptions below "
            "are transcribed schema declarations, not independent certification of runtime behavior.",
            "",
        ])
        if any("class token" in s.get("condition_human", "") for s in sections
               if s.get("condition_key") == "has_measured_assembly_line"):
            lines.extend([
                "**Unresolved predicate-description hold:** the default JSON's "
                "`has_measured_assembly_line` descriptions still mention PKS/NRPS class tokens, "
                "while the native predicate requires measured module evidence/flags and excludes "
                "class labels alone. The source JSON is preserved here; do not treat the old "
                "class-token clause as a measured observation. See MODEB_CONTRACT_HISTORY_AND_GATE_SCOPE.md.",
                "",
            ])
        lines.extend([
            "| § | Predicate key | Triggers when |",
            "|---|---|---|",
        ])
        for s in cond_sections:
            lines.append(
                f"| {s['number']} | `{s.get('condition_key','—')}` | "
                f"{s.get('condition_human','—')} |"
            )

    # Section sub-questions (LQ-MODEB-02): deepen an existing section with named prompts the
    # author theorises over. Additive to the §1-§30 structure — no new section, no gate change.
    sq_sections = [s for s in sections if s.get("sub_questions")]
    if sq_sections:
        lines.extend([
            "",
            "## Section sub-questions",
            "",
            "Named prompts that deepen an existing section (no new section is added). The template "
            "emitter renders them for the author; the depth gate treats them as WARN-only.",
            "",
        ])
        for s in sq_sections:
            lines.append(f"**§{s['number']} — {s['title']}**")
            for q in s["sub_questions"]:
                lines.append(f"- {q}")
            lines.append("")

    # Quality gate
    if quality_gate:
        lines.extend([
            "",
            "## Quality gate",
            "",
            "These are the unchanged requirements declared by the selected JSON. This list "
            "is not a complete enforcement map: inspect the selected profile, verifier options "
            "and actual findings, and retain independent source/content review separately.",
            "",
        ])
        for i, line in enumerate(quality_gate, start=1):
            lines.append(f"{i}. {line}")

    # Artifact-drift policy
    drift = contract.get("artifact_drift_policy") or {}
    if drift:
        lines.extend([
            "",
            "## Artifact-drift policy",
            "",
        ])
        for k, v in drift.items():
            lines.append(f"- **`{k}`:** {v}")

    lines.extend([
        "",
        "## Single source of truth (W9-C / N10)",
        "",
        f"Before v9.7.150e there were six §1–§20 schema sources in the bundle (two JSON "
        f"files, a hard-coded fallback in `mamey/modeb_structure_gate.py`, an archival "
        f"legacy JSON, and two handwritten markdown docs). N10 collapsed that surface: "
        f"The historical filename `modeb_full30_corrective_contract.json` now owns the default "
        f"full48 corrective schema. It is not the separate opt-in current50_v2 schema. "
        f"This document and `MODE_B_30_SECTION_CANONICAL_TITLES.md` are generated by "
        f"`tools/regen_modeb_contract_docs.py`. The `mamey/modeb_structure_gate.py` "
        f"facade derives its §1–§20 sections via "
        f"`mamey.modeb_structure_gate.load_contract()`. Run "
        f"`tools/regen_modeb_contract_docs.py --check` in CI to enforce no drift.",
        "",
    ])
    return "\n".join(lines) + "\n"


