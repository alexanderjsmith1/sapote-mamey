#!/usr/bin/env python3
"""regen_modeb_contract_docs.py — regenerate Mode B contract docs from the JSON.

Reads `mamey/data/mode_b/modeb_full30_corrective_contract.json` (the single
default full48 schema; its full30 filename is historical) and emits two markdown documents:

  - `docs/MODE_B_30_SECTION_CANONICAL_TITLES.md`
      Section-titles-only doc — for chats and humans browsing the contract.

  - `docs/FULL_MODEB_30_SECTION_CONTRACT_v97150.md`
      Full contract spec — required/conditional, predicate descriptions,
      quality-gate checklist.

These docs were previously handwritten alongside the JSON. Drift between
contract data and contract docs is the failure mode N10 documented after the
v9.7.150d cut showed six §1–§20 schema sources in the bundle. This tool
collapses the default corrective surface: preserve JSON requirements, edit generator prose
when needed, regenerate and retain the separate current50_v2 contract owner.

Usage:
    python3 tools/regen_modeb_contract_docs.py
        # regenerates both docs in place

    python3 tools/regen_modeb_contract_docs.py --check
        # exits 0 if both docs match what would be generated; 1 if drift
        # exists. Use in CI to enforce "JSON is source of truth."

    python3 tools/regen_modeb_contract_docs.py --titles-out <path>
                                                --contract-out <path>
        # write to non-default locations (for testing)

W9-C / N10 (v9.7.150e+).
"""
