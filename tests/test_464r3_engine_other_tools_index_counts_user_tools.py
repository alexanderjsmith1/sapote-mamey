"""deliverable_tools index: unittest modules are not counted as user tools, and the shipped index is current.

Before: `test_related.py` was listed (and counted in "45 tools") as a dispatchable tool, and the
clade_ani row presented threshold labels as "sign-off species-boundary calls".
"""
import importlib.util
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
TOOLS = ROOT / "deliverable_tools"


def _cohort_tools():
    spec = importlib.util.spec_from_file_location("_cohort_tools_464r3", TOOLS / "cohort_tools.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_unittest_modules_are_not_tools():
    names = [name for name, _ in _cohort_tools()._tools()]
    assert not [n for n in names if n.startswith("test_")]


def test_shipped_index_count_and_rows_match_the_generator():
    tools = _cohort_tools()._tools()
    index = (TOOLS / "TOOLS_INDEX.md").read_text(encoding="utf-8")
    assert f"Auto-generated by `cohort_tools.py index`. {len(tools)} tools." in index
    assert "`test_related`" not in index
    assert "sign-off species-boundary calls" not in index
