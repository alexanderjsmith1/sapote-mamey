"""Shipped tool descriptions carry no cohort counts.

`deliverable_tools/TOOLS_INDEX.md` is generated by `cohort_tools.py index` from each tool's
docstring. The `rebuild_cohort_comparison` row used to print real cohort sizes. The release
default is PRIVATE, so the docstring uses neutral placeholders and the index row follows it.
"""
import importlib.util
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
TOOLS = ROOT / "deliverable_tools"
COUNT = re.compile(r"\b\d+\s+(?:SID|AS)\b")


def _cohort_tools():
    spec = importlib.util.spec_from_file_location("_cohort_tools_458", TOOLS / "cohort_tools.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_generator_source_has_no_cohort_counts():
    desc = _cohort_tools()._describe(str(TOOLS / "rebuild_cohort_comparison.py"))
    assert not COUNT.search(desc), desc


def test_tools_index_row_matches_generator_and_has_no_counts():
    index = (TOOLS / "TOOLS_INDEX.md").read_text(encoding="utf-8")
    assert not COUNT.search(index), COUNT.findall(index)
    desc = _cohort_tools()._describe(str(TOOLS / "rebuild_cohort_comparison.py"))
    row = "| `rebuild_cohort_comparison` | " + desc.replace("|", "\\|") + " |"
    assert row in index.splitlines()
